--CODIGO 2: Creacion de las 20 tablas de PostgreSQL (sin FK)

CREATE TABLE Inventario (
    id_inventario   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sucursal     BIGINT NOT NULL,
    nombre          VARCHAR(100) NOT NULL,
    descripcion     VARCHAR(250),
    estado          VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
                        CHECK (estado IN ('ACTIVO','INACTIVO'))
);

CREATE TABLE Almacen (
    id_almacen      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_inventario   BIGINT NOT NULL,
    nombre          VARCHAR(100) NOT NULL,
    descripcion     VARCHAR(250),
    ubicacion       VARCHAR(200),
    estado          VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
                        CHECK (estado IN ('ACTIVO','INACTIVO'))
);

CREATE TABLE UbicacionProducto (
    id_ubicacion      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_almacen        BIGINT NOT NULL,
    id_sku            BIGINT NOT NULL,
    codigo_ubicacion  VARCHAR(50) NOT NULL,
    descripcion       VARCHAR(200),
    estado            VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
                          CHECK (estado IN ('ACTIVO','INACTIVO')),
    CONSTRAINT uq_ubicacion_codigo UNIQUE (id_almacen, codigo_ubicacion)
);

CREATE TABLE Stock (
    id_stock              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ubicacion          BIGINT NOT NULL,
    id_sku                BIGINT NOT NULL,
    cantidad_actual       NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (cantidad_actual >= 0),
    cantidad_reservada    NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (cantidad_reservada >= 0),
    cantidad_disponible   NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (cantidad_disponible >= 0),
    fecha_actualizacion   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_stock_ubicacion_sku UNIQUE (id_ubicacion, id_sku)
);

CREATE TABLE MovimientoInventario (
    id_movimiento       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_stock            BIGINT NOT NULL,
    id_tipo_movimiento  INTEGER NOT NULL,
    cantidad            NUMERIC(12,2) NOT NULL CHECK (cantidad <> 0),
    fecha_movimiento    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    observacion         VARCHAR(250)
);

CREATE TABLE TipoMovimiento (
    id_tipo_movimiento  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(50) NOT NULL UNIQUE,
    descripcion         VARCHAR(200),
    afecta_stock        BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE CodigoBarras (
    id_codigo_barras  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sku            BIGINT NOT NULL,
    codigo            VARCHAR(100) NOT NULL UNIQUE,
    tipo_codigo       VARCHAR(30) NOT NULL,
    estado            VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
                          CHECK (estado IN ('ACTIVO','INACTIVO'))
);

CREATE TABLE AlertaReabastecimiento (
    id_alerta            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_stock             BIGINT NOT NULL,
    id_configuracion     BIGINT NOT NULL,
    fecha_alerta         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    cantidad_detectada   NUMERIC(12,2) NOT NULL,
    estado               VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
                              CHECK (estado IN ('PENDIENTE','RESUELTA','CANCELADA')),
    fecha_resolucion     TIMESTAMP
);

CREATE TABLE ConfiguracionReabastecimiento (
    id_configuracion            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sku                      BIGINT NOT NULL,
    stock_minimo                NUMERIC(12,2) NOT NULL CHECK (stock_minimo >= 0),
    stock_maximo                NUMERIC(12,2) NOT NULL CHECK (stock_maximo >= 0),
    cantidad_reabastecimiento   NUMERIC(12,2) NOT NULL CHECK (cantidad_reabastecimiento > 0),
    estado                      VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
                                    CHECK (estado IN ('ACTIVO','INACTIVO')),
    CONSTRAINT chk_config_min_max CHECK (stock_maximo >= stock_minimo)
);

CREATE TABLE Devolucion (
    id_devolucion      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta           BIGINT NOT NULL,
    id_empleado        BIGINT NOT NULL,
    fecha_devolucion   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    motivo             VARCHAR(250) NOT NULL,
    estado             VARCHAR(20) NOT NULL DEFAULT 'REGISTRADA'
                            CHECK (estado IN ('REGISTRADA','APROBADA','RECHAZADA'))
);

CREATE TABLE DetalleDevolucion (
    id_detalle_devolucion  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_devolucion          BIGINT NOT NULL,
    id_sku                 BIGINT NOT NULL,
    cantidad               NUMERIC(12,2) NOT NULL CHECK (cantidad > 0),
    motivo                 VARCHAR(250)
);

CREATE TABLE Promocion (
    id_promocion      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(150) NOT NULL,
    descripcion       VARCHAR(300),
    tipo_descuento    VARCHAR(20) NOT NULL
                          CHECK (tipo_descuento IN ('PORCENTAJE','MONTO_FIJO')),
    valor_descuento   NUMERIC(10,2) NOT NULL CHECK (valor_descuento > 0),
    fecha_inicio      TIMESTAMP NOT NULL,
    fecha_fin         TIMESTAMP NOT NULL,
    estado            VARCHAR(20) NOT NULL DEFAULT 'ACTIVA'
                          CHECK (estado IN ('ACTIVA','INACTIVA','FINALIZADA')),
    CONSTRAINT chk_promocion_fechas CHECK (fecha_fin > fecha_inicio)
);

CREATE TABLE ProductoPromocion (
    id_producto_promocion  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_promocion           BIGINT NOT NULL,
    id_sku                 BIGINT NOT NULL,
    estado                 VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
                                CHECK (estado IN ('ACTIVO','INACTIVO')),
    CONSTRAINT uq_producto_promocion UNIQUE (id_promocion, id_sku)
);

CREATE TABLE HistorialStock (
    id_historial        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_stock             BIGINT NOT NULL,
    cantidad_anterior    NUMERIC(12,2) NOT NULL,
    cantidad_nueva       NUMERIC(12,2) NOT NULL,
    fecha_cambio         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    motivo               VARCHAR(250)
);

CREATE TABLE TransferenciaInventario (
    id_transferencia      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_almacen_origen     BIGINT NOT NULL,
    id_almacen_destino    BIGINT NOT NULL,
    fecha_transferencia   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    estado                VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
                               CHECK (estado IN ('PENDIENTE','EN_TRANSITO','COMPLETADA','CANCELADA')),
    observacion           VARCHAR(250),
    CONSTRAINT chk_transferencia_almacenes CHECK (id_almacen_origen <> id_almacen_destino)
);

CREATE TABLE DetalleTransferencia (
    id_detalle_transferencia  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transferencia          BIGINT NOT NULL,
    id_sku                    BIGINT NOT NULL,
    cantidad                  NUMERIC(10,2) NOT NULL CHECK (cantidad > 0)
);

CREATE TABLE ConteoInventario (
    id_conteo       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_almacen      BIGINT NOT NULL,
    fecha_conteo    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    responsable     BIGINT,
    estado          VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
                        CHECK (estado IN ('PENDIENTE','EN_PROCESO','FINALIZADO')),
    observacion     VARCHAR(250)
);

CREATE TABLE DetalleConteoInventario (
    id_detalle_conteo   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conteo           BIGINT NOT NULL,
    id_sku               BIGINT NOT NULL,
    cantidad_sistema    NUMERIC(10,2) NOT NULL,
    cantidad_contada    NUMERIC(10,2) NOT NULL,
    diferencia          NUMERIC(10,2) NOT NULL
);

CREATE TABLE LoteProducto (
    id_lote              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sku               BIGINT NOT NULL,
    numero_lote          VARCHAR(50) NOT NULL,
    fecha_ingreso        DATE DEFAULT CURRENT_DATE,
    fecha_vencimiento    DATE,
    estado               VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
                             CHECK (estado IN ('ACTIVO','INACTIVO','VENCIDO')),
    CONSTRAINT uq_lote_sku_numero UNIQUE (id_sku, numero_lote)
);

CREATE TABLE DetalleLote (
    id_detalle_lote   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_lote           BIGINT NOT NULL,
    id_ubicacion      BIGINT NOT NULL,
    cantidad          NUMERIC(10,2) NOT NULL CHECK (cantidad >= 0)
);

